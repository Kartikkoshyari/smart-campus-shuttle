import { routes, shuttles, simulationProfiles, stops } from '../src/data/campus.ts'
import { stopVisits } from '../src/simulator/timeline.ts'
import { getTimeline } from '../src/simulator/timetables.ts'

/**
 * Builds supabase/seed.sql from the demo data in src/data/campus.ts and the
 * timetables the app's simulator calculates. Generating it (instead of typing
 * it) keeps the database and the app in exact agreement.
 */

function text(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

function num(value: number): string {
  return Number(value.toFixed(3)).toString()
}

export function buildSeedSql(): string {
  const lines: string[] = [
    '-- Smart Campus Shuttle demo data.',
    '-- GENERATED by scripts/generate-seed.ts from src/data/campus.ts. Do not edit by hand:',
    '-- change src/data/campus.ts, then run `npm run db:seed`.',
    '-- Coordinates are for demonstration only. They do not show a real campus.',
    '-- Safe to run more than once. Re-running restores the demo shuttles, including their capacity.',
    '',
    'begin;',
    '',
    'insert into public.routes (id, name, is_loop, allows_reverse) values',
    routes.map((r) => `  (${text(r.id)}, ${text(r.name)}, ${r.isLoop}, ${r.allowsReverse})`).join(',\n'),
    'on conflict (id) do update set name = excluded.name, is_loop = excluded.is_loop, allows_reverse = excluded.allows_reverse;',
    '',
    'insert into public.stops (id, name, code, lat, lng) values',
    stops
      .map((s) => `  (${text(s.id)}, ${text(s.name)}, ${text(s.code)}, ${s.position.lat}, ${s.position.lng})`)
      .join(',\n'),
    'on conflict (id) do update set name = excluded.name, code = excluded.code, lat = excluded.lat, lng = excluded.lng;',
    '',
    `delete from public.route_stops where route_id in (${routes.map((r) => text(r.id)).join(', ')});`,
    'insert into public.route_stops (route_id, stop_id, position) values',
    routes
      .flatMap((r) => r.stopIds.map((stopId, position) => `  (${text(r.id)}, ${text(stopId)}, ${position})`))
      .join(',\n') + ';',
    '',
    'insert into public.shuttles (id, code, name, route_id, direction, capacity, speed_mps, dwell_seconds, start_offset_seconds, cycle_seconds) values',
    shuttles
      .map((s) => {
        const profile = simulationProfiles[s.id]
        return `  (${text(s.id)}, ${text(s.code)}, ${text(s.name)}, ${text(s.routeId)}, ${text(s.direction)}, ${s.capacity}, ${num(profile.speedMps)}, ${num(profile.dwellSeconds)}, ${num(profile.startOffsetSeconds)}, ${num(getTimeline(s.id).cycleSeconds)})`
      })
      .join(',\n'),
    'on conflict (id) do update set code = excluded.code, name = excluded.name, route_id = excluded.route_id,',
    '  direction = excluded.direction, capacity = excluded.capacity, speed_mps = excluded.speed_mps,',
    '  dwell_seconds = excluded.dwell_seconds, start_offset_seconds = excluded.start_offset_seconds,',
    '  cycle_seconds = excluded.cycle_seconds, updated_at = now();',
    '',
    `delete from public.shuttle_visits where shuttle_id in (${shuttles.map((s) => text(s.id)).join(', ')});`,
    'insert into public.shuttle_visits (shuttle_id, visit_index, stop_id, arrive_at, depart_at) values',
    shuttles
      .flatMap((s) =>
        stopVisits(getTimeline(s.id)).map(
          (v) => `  (${text(s.id)}, ${v.index}, ${text(v.stopId)}, ${num(v.arriveAt)}, ${num(v.departAt)})`,
        ),
      )
      .join(',\n') + ';',
    '',
    '-- Every shuttle starts moving straight away. Existing clocks are left alone.',
    'insert into public.shuttle_clocks (shuttle_id) values',
    shuttles.map((s) => `  (${text(s.id)})`).join(',\n'),
    'on conflict (shuttle_id) do nothing;',
    '',
    'commit;',
    '',
  ]
  return lines.join('\n')
}
