-- Smart Campus Shuttle: tables
--
-- Run the migrations in file-name order (see README, "Supabase setup").
-- Network data (routes, stops, shuttles, timetables) is public. Profiles and
-- bookings are private and protected by Row Level Security (third migration).

-- Routes and stops -----------------------------------------------------------

create table public.routes (
  id text primary key,
  name text not null check (char_length(name) between 1 and 80),
  is_loop boolean not null default true,
  allows_reverse boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.stops (
  id text primary key,
  name text not null check (char_length(name) between 1 and 80),
  code text not null unique check (char_length(code) between 1 and 4),
  -- Demo coordinates only. They do not show a real campus.
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  created_at timestamptz not null default now()
);

-- The order of stops on a route (clockwise).
create table public.route_stops (
  route_id text not null references public.routes (id) on delete cascade,
  stop_id text not null references public.stops (id),
  position integer not null check (position >= 0),
  primary key (route_id, stop_id),
  unique (route_id, position)
);

-- Shuttles and their simulated timetable ------------------------------------

create table public.shuttles (
  id text primary key,
  code text not null unique check (char_length(code) between 1 and 12),
  name text not null check (char_length(name) between 1 and 80),
  route_id text not null references public.routes (id),
  direction text not null check (direction in ('clockwise', 'anticlockwise')),
  capacity integer not null check (capacity between 1 and 100),
  speed_mps numeric not null check (speed_mps > 0),
  dwell_seconds numeric not null check (dwell_seconds >= 0),
  start_offset_seconds numeric not null default 0,
  -- Seconds for one full run at 1x speed (generated from the app's simulator).
  cycle_seconds numeric not null check (cycle_seconds > 0),
  -- Goes up whenever seats change, so screens know to refresh seat counts.
  seat_version bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Every stop visit in one run, in order. The first stop appears again at the
-- end, because a run ends where it started. Generated by scripts/generate-seed.ts.
create table public.shuttle_visits (
  shuttle_id text not null references public.shuttles (id) on delete cascade,
  visit_index integer not null check (visit_index >= 0),
  stop_id text not null references public.stops (id),
  arrive_at numeric not null check (arrive_at >= 0),
  depart_at numeric not null,
  primary key (shuttle_id, visit_index),
  check (depart_at >= arrive_at)
);

-- The simulation clock for each shuttle. Position = timetable + clock + time now.
create table public.shuttle_clocks (
  shuttle_id text primary key references public.shuttles (id) on delete cascade,
  run_state text not null default 'running' check (run_state in ('idle', 'running', 'paused')),
  speed integer not null default 1 check (speed in (1, 2, 5)),
  base_elapsed numeric not null default 0 check (base_elapsed >= 0),
  base_time timestamptz not null default now(),
  -- Goes up by one on every reset. Bookings made before a reset end with it.
  generation integer not null default 0 check (generation >= 0),
  updated_by uuid references auth.users (id) on delete set null,
  updated_at timestamptz not null default now()
);

-- People ---------------------------------------------------------------------

-- One row per account, created automatically on sign-up (second migration).
-- The role is NEVER taken from the browser: everyone starts as a student.
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null check (char_length(full_name) between 1 and 120),
  email text not null default '',
  role text not null default 'student' check (role in ('student', 'operator', 'admin')),
  assigned_shuttle_id text references public.shuttles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint only_operators_have_shuttles check (assigned_shuttle_id is null or role = 'operator')
);

-- Bookings -------------------------------------------------------------------

create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^SCS-[ABCDEFGHJKMNPQRSTUVWXYZ23456789]{6}$'),
  user_id uuid not null references public.profiles (id) on delete cascade,
  passenger_name text not null,
  shuttle_id text not null references public.shuttles (id),
  pickup_stop_id text not null references public.stops (id),
  destination_stop_id text not null references public.stops (id),
  status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
  generation integer not null check (generation >= 0),
  -- Simulated seconds since the shuttle's last reset.
  pickup_arrival_elapsed numeric not null,
  pickup_departure_elapsed numeric not null,
  dropoff_elapsed numeric not null,
  created_at timestamptz not null default now(),
  cancelled_at timestamptz,
  check (pickup_stop_id <> destination_stop_id),
  check (pickup_departure_elapsed >= pickup_arrival_elapsed),
  check (dropoff_elapsed > pickup_departure_elapsed),
  check ((status = 'cancelled') = (cancelled_at is not null))
);

create index bookings_user_created_idx on public.bookings (user_id, created_at desc);
create index bookings_shuttle_active_idx on public.bookings (shuttle_id, status, generation);
create index route_stops_route_position_idx on public.route_stops (route_id, position);
